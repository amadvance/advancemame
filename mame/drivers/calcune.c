static READ16_HANDLER(calcune_select_r)
{
	calcune_vdp_select(0);
	return 0;
}

static WRITE16_HANDLER(calcune_select_w)
{
	calcune_vdp_select(data);
}

static READ16_HANDLER(calcune_sound_r)
{
	return YMZ280B_data_0_r(0) << 8;
}

