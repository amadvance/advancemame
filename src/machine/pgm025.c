static UINT16 prot_hold, prot_hilo, prot_select, prot_cmd, prot_reg, prot_swap;
static UINT32 prot_id;
static unsigned prot_ptr, prot_region;
static int prot_dma;
static const UINT8 (*prot_source)[0xec];
static UINT16 *prot_ram;
static UINT32 prot_regs[0x300], prot_stack[0x100];
static unsigned prot_stack_ptr;

void pgm_025_configure(unsigned region, int with_dma)
{
	prot_region = region;
	prot_dma = with_dma;
	prot_source = with_dma ? dw3_source_data : drgw2_source_data;
	prot_id = with_dma ? (0x00060000 | region) : region * 0x01010101;
}

void pgm_025_reset(void)
{
	prot_hold = prot_hilo = prot_select = prot_cmd = prot_reg = prot_swap = 0;
	prot_ptr = 0;
}

static void pgm_022_dma(UINT16 src, UINT16 dst, UINT16 size, UINT16 mode)
{
	const UINT16 *rom = (UINT16 *)memory_region(REGION_USER1);
	const UINT8 *table = memory_region(REGION_USER1);
	const UINT16 letters[4] = { 0x49, 0x47, 0x53, 0x20 };
	unsigned param = mode >> 8;
	unsigned x;

	mode &= 7;
	if (mode == 7)
		return;
	for (x = 0; x < size; ++x)
	{
		UINT16 data = rom[src + x];
		unsigned off = (x * 2 + param) & 0xff;
		UINT16 extra = table[off] | (table[off + 1] << 8);

		switch (mode)
		{
		case 1: data -= extra; break;
		case 2: data += extra; break;
		case 3: data ^= extra; break;
		case 4: data -= letters[x & 3] | (letters[(x >> 8) & 3] << 8); break;
		case 5: data = (data << 8) | (data >> 8); break;
		case 6: data = ((data & 0xf0f0) >> 4) | ((data & 0x0f0f) << 4); break;
		}
		prot_ram[dst + x] = data;
	}
}

void pgm_022_reset(UINT16 *ram)
{
	const UINT16 *rom = (UINT16 *)memory_region(REGION_USER1);
	UINT16 mode = rom[0x106 / 2];
	unsigned i;

	prot_ram = ram;
	memset(prot_regs, 0, sizeof(prot_regs));
	memset(prot_stack, 0, sizeof(prot_stack));
	prot_stack_ptr = 0;
	for (i = 0; i < 0x4000 / 2; ++i)
		prot_ram[i] = 0xa55a;
	mode = (mode << 8) | (mode >> 8);
	pgm_022_dma(rom[0x100 / 2] >> 1, rom[0x102 / 2], rom[0x104 / 2], mode);
	prot_ram[0x2a2 / 2] = rom[0x114 / 2];
}

static void pgm_022_push(UINT32 value)
{
	if (prot_stack_ptr < 0xff)
		++prot_stack_ptr;
	prot_stack[prot_stack_ptr] = value;
}

static UINT32 pgm_022_pop(void)
{
	UINT32 value = prot_stack[prot_stack_ptr];
	if (prot_stack_ptr)
		--prot_stack_ptr;
	return value;
}

static UINT32 pgm_022_read_reg(UINT16 reg)
{
	if (reg < 0x300)
		return prot_regs[reg];
	if (reg == 0x400)
		return pgm_022_pop();
	return 0;
}

static void pgm_022_write_reg(UINT16 reg, UINT32 value)
{
	if (reg < 0x300)
		prot_regs[reg] = value;
	else if (reg == 0x300)
		pgm_022_push(value);
}

static void pgm_022_command(void)
{
	UINT16 command = prot_ram[0x200 / 2];
	switch (command)
	{
	case 0x12:
		pgm_022_push(((UINT32)prot_ram[0x288 / 2] << 16) | prot_ram[0x28a / 2]);
		prot_ram[0x202 / 2] = 0x23;
		break;
	case 0x2d:
		prot_ram[0x202 / 2] = 0x3c;
		break;
	case 0x45:
	{
		UINT32 value = pgm_022_pop();
		prot_ram[0x28c / 2] = value >> 16;
		prot_ram[0x28e / 2] = value;
		prot_ram[0x202 / 2] = 0x56;
		break;
	}
	case 0x4f:
		pgm_022_dma(prot_ram[0x290 / 2] >> 1, prot_ram[0x292 / 2], prot_ram[0x294 / 2], prot_ram[0x296 / 2]);
		prot_ram[0x202 / 2] = 0x5e;
		break;
	case 0x5a:
		prot_ram[0x202 / 2] = 0x4b;
		break;
	case 0x6d:
	{
		UINT32 p1 = ((UINT32)prot_ram[0x298 / 2] << 16) | prot_ram[0x29a / 2];
		UINT32 p2 = ((UINT32)prot_ram[0x29c / 2] << 16) | prot_ram[0x29e / 2];
		UINT16 src1 = p1 >> 16, src2 = p1, dst = p2 >> 16;
		UINT32 value;

		switch (p2 & 0xffff)
		{
		case 0:
			value = pgm_022_read_reg(src1) + pgm_022_read_reg(src2);
			pgm_022_write_reg(dst, value);
			break;
		case 1:
			value = pgm_022_read_reg(src1) - pgm_022_read_reg(src2);
			pgm_022_write_reg(dst, value);
			break;
		case 6:
			value = pgm_022_read_reg(src2) - pgm_022_read_reg(src1);
			pgm_022_write_reg(dst, value);
			break;
		case 9:
			pgm_022_write_reg(dst, p1);
			break;
		case 0xa:
			value = pgm_022_read_reg(src1);
			prot_ram[0x29c / 2] = value >> 16;
			prot_ram[0x29e / 2] = value;
			break;
		}
		prot_ram[0x202 / 2] = 0x7c;
		break;
	}
	}
}

WRITE16_HANDLER(pgm_025_w)
{
	if (!offset)
	{
		prot_cmd = data;
		return;
	}
	if (prot_cmd >= 0x20 && prot_cmd <= 0x27)
	{
		UINT16 old = prot_hold;
		++prot_ptr;
		prot_hold = (old << 1) | (old >> 15);
		prot_hold ^= 0x2bad;
		prot_hold ^= BIT(data, prot_cmd & 0xf);
		prot_hold ^= BIT(old, 7);
		prot_hold ^= BIT(~old, 13) << 4;
		prot_hold ^= BIT(old, 3) << 11;
		prot_hold ^= (prot_hilo & ~0x0408) << 1;
	}
	else if (prot_dma)
	{
		switch (prot_cmd)
		{
		case 0: prot_reg = data; break;
		case 1: if (data == 2) pgm_022_command(); break;
		case 2: if (data == 1) { pgm_022_command(); ++prot_reg; } break;
		case 3: prot_swap = data; break;
		}
	}
}

READ16_HANDLER(pgm_025_r)
{
	if (offset)
	{
		switch (prot_cmd)
		{
		case 0: return BITSWAP8((prot_swap + 1) & 0x7f, 0,1,2,3,4,5,6,7);
		case 1: return prot_reg & 0x7f;
		case 2: return 0x80;
		case 5:
			if (prot_ptr >= 1 && prot_ptr <= 4)
				return 0x3f00 | ((prot_id >> ((prot_ptr - 1) * 8)) & 0xff);
			return 0x3f00 | BITSWAP8(prot_hold, 5,2,9,7,10,13,12,15);
		case 0x40:
		{
			UINT8 source;
			if (++prot_select > 0xeb)
				prot_select = 0;
			source = prot_source[prot_region][prot_select];
			if (prot_select & 1)
				prot_hilo = (prot_hilo & 0x00ff) | (source << 8);
			else
				prot_hilo = (prot_hilo & 0xff00) | source;
			break;
		}
		}
	}
	return 0;
}
